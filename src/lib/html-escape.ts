/** Shared HTML-escaping for server-rendered markup built from untrusted or
 *  semi-trusted text (AI output, merchant catalog data). */
export function escapeHtml(value: string): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
